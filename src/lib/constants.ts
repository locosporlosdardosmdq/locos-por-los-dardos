export function calculateCategory(avg: number): PlayerCategory {
  if (avg >= 70) return 'ELITE';
  if (avg >= 55) return 'AVANZADA';
  if (avg >= 40) return 'INTERMEDIA';
  return 'PRINCIPIANTE';
}

